import turtle
t= turtle.Turtle()
#change the turtle shape to a turtle
t.shape("turtle")
#change the turtle color to green
t.color("green")
#change the turtle speed to 1
t.speed(1)
#change the turtle size to 2
t.turtlesize(2)
#change the turtle pen size to 5
t.pensize(5)
#change the turtle pen color to red
t.pencolor("red")
#stop the turtle from drawing when it moves
t.penup()


t.forward(100)

#stop the close window
turtle.done()


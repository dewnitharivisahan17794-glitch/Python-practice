#Escape Characters
print("Hello\nWorld") # \n is a new line character(line break)
print("Hello\tWorld") # \t is a tab character(long space)
print("Wellcome\rworld") # \r is a carriage return character(moves the cursor to the beginning of the line,overwriting the existing text"Worldewa" will overwrite "Helloewa" ) 
print("Hello\bWorld") # \b is a backspace character(deletes the previous character)


#print function with Escape Characters
print("Hello\nWorld") # Output: Hello (new line) World 
print("Hello\tWorld") # Output: Hello (tab space) World
print("Wellcome\rworld") # Output: world (overwrites "Hello")
print("Hello\bWorld") # Output: HelloWorld (backspace deletes the space between "Hello" and "World")

